<?php

/*
|--------------------------------------------------------------------------
| CSRF
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| GARANTIR SESSÃO
|--------------------------------------------------------------------------
*/

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}


/*
|--------------------------------------------------------------------------
| GERAR TOKEN
|--------------------------------------------------------------------------
*/

if (
    empty($_SESSION['csrf_token'])
) {

    $_SESSION['csrf_token'] =
        bin2hex(
            random_bytes(32)
        );

}


/*
|--------------------------------------------------------------------------
| OBTER TOKEN
|--------------------------------------------------------------------------
*/

function csrf_token(): string
{
    return $_SESSION['csrf_token'];
}


/*
|--------------------------------------------------------------------------
| VALIDAR TOKEN
|--------------------------------------------------------------------------
*/

function csrf_validate(
    ?string $token
): bool {

    if (
        empty($token) ||
        empty($_SESSION['csrf_token'])
    ) {
        return false;
    }


    return hash_equals(
        $_SESSION['csrf_token'],
        $token
    );
}